package com.bankhub.investment.domain;

/**
 * Representa os tipos de ativos financeiros suportados pelo Bank-Hub.
 */
public enum AssetType {
    CDB,    // Certificado de Depósito Bancário (Renda Fixa)
    STOCK,  // Ações da Bolsa de Valores (Ex: PETR4, VALE3)
    FII     // Fundos de Investimento Imobiliário (Ex: HGLG11)
}
